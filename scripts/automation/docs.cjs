const fs = require('fs');
const path = require('path');
const pkg = require('../../package.json');
function files(dir) {
    return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? files(path.join(dir, entry.name)) : [path.join(dir, entry.name)]);
}
const sources = files('src').filter(file => /\.[jt]sx?$/.test(file) && !file.includes('.test.'));
const env = [...new Set(sources.flatMap(file => [...fs.readFileSync(file, 'utf8').matchAll(/process\.env\.(REACT_APP_\w+)/g)].map(match => match[1])))].sort();
const routes = [...fs.readFileSync('src/App.js', 'utf8').matchAll(/<Route\s+path="([^"]+)"/g)].map(match => match[1]);
const content = `<!-- Generated by npm run docs:generate. Edit source files, then regenerate. -->
# Repository reference

## Commands

| Command | Runs |
| --- | --- |
${Object.entries(pkg.scripts).map(([name, command]) => `| \`npm run ${name}\` | \`${command}\` |`).join('\n')}

## Browser configuration

These names are compiled into the browser bundle. Never use service-role keys or private credentials here.

${env.map(name => `- \`${name}\``).join('\n')}

## Declared routes

Parameterized routes require a real identifier. Staff routes are also generated from staffData.js.

${routes.map(route => `- \`${route}\``).join('\n')}

## Content inventory

- Article text files: ${files('src/Data/articleTexts').filter(file => file.endsWith('.json')).length}
- Public PDFs: ${files('public').filter(file => /\.pdf$/i.test(file)).length}
`;
const target = 'docs/REPOSITORY_REFERENCE.md';
if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) throw new Error('Repository reference is stale. Run npm run docs:generate.');
} else fs.writeFileSync(target, content);
